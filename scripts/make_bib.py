#!/usr/bin/env python3
"""Generate docs/references.bib from verified metadata only.

Sources:
  docs/research/doi_verification.json   (Crossref-registered metadata; only verdict == VERIFIED is used)
  docs/research/manual_references.json  (non-DOI items: preprints, tech reports, official docs)

Nothing is typed by hand into the .bib file, so the bibliography cannot drift from the evidence.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "docs" / "research"
OUT = ROOT / "docs" / "references.bib"

TYPE_MAP = {
    "journal-article": ("article", "journal"),
    "proceedings-article": ("inproceedings", "booktitle"),
    "book-chapter": ("incollection", "booktitle"),
    "report": ("techreport", "institution"),
}


def esc(s: str) -> str:
    return str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def entry(kind: str, key: str, fields: dict) -> str:
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields.items() if v not in (None, ""))
    return f"@{kind}{{{key},\n{body}\n}}\n"


def main() -> int:
    out = ["% SETU-X bibliography. GENERATED by scripts/make_bib.py. Do not edit by hand.\n",
           "% DOI entries: metadata as registered in Crossref (checked by scripts/verify_references.py).\n\n"]
    n = 0
    for r in json.loads((RES / "doi_verification.json").read_text(encoding="utf-8")):
        if r.get("verdict") != "VERIFIED":
            print(f"skipping unverified {r['id']} ({r.get('verdict')})", file=sys.stderr)
            continue
        g = r["registered"]
        kind, venue_field = TYPE_MAP.get(g.get("type"), ("misc", "howpublished"))
        title = g["title"]
        if r["id"] == "mell2011nist":  # Crossref stores a lower-case title; keep NIST's official capitalisation
            title = "The {NIST} Definition of Cloud Computing"
        fields = {
            "title": "{" + esc(title) + "}" if r["id"] != "mell2011nist" else title,
            "author": " and ".join(esc(a) for a in g["authors"]),
            "year": g["year"],
            venue_field: esc(g["venue"]),
            "volume": g.get("volume"),
            "number": g.get("issue"),
            "pages": (g.get("pages") or "").replace("-", "--") or None,
            "publisher": esc(g.get("publisher") or ""),
            "doi": r["doi"],
        }
        if r["id"] == "mell2011nist":
            fields["number"] = "Special Publication 800-145"
        out.append(entry(kind, r["id"], fields))
        n += 1
    out.append("\n% Non-DOI sources (preprints, technical reports, official documentation).\n\n")
    for m in json.loads((RES / "manual_references.json").read_text(encoding="utf-8")):
        kind = {"online": "misc", "techreport": "techreport", "misc": "misc",
                "inproceedings": "inproceedings"}[m["type"]]
        venue_field = {"techreport": "institution", "inproceedings": "booktitle"}.get(kind, "howpublished")
        fields = {
            "title": "{" + esc(m["title"]) + "}",
            "author": " and ".join(m["authors"]),
            "year": m["year"],
            venue_field: esc(m["venue"]),
            "pages": m.get("pages"),
            "publisher": m.get("publisher"),
            "url": m["url"],
            "urldate": m.get("urldate"),
            "note": esc(m["note"]) if m.get("note") else None,
        }
        out.append(entry(kind, m["id"], fields))
        n += 1
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {n} entries to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
